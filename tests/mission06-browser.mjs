import {chromium,firefox} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
const sample='Seit du in meinem Leben bist, ist alles ein bisschen heller geworden. Ich liebe dich von ganzem Herzen, mein Schatz Katharina. ❤️ Und jeder Tag mit dir ist besonders schön.\nFür immer, mein Herz!';
const root='http://127.0.0.1:8000/';
await mkdir('tests/artifacts',{recursive:true});
for(const [name,driver] of [['chromium',chromium],['firefox',firefox]]){
 const browser=await driver.launch({headless:true});
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 try{
 const page=await context.newPage(),errors=[];
 page.on('pageerror',err=>errors.push(err.message));
 await page.goto(root,{waitUntil:'domcontentloaded'});
 await page.locator('#mirrorDensity').selectOption('666');
 assert.match(await page.locator('#mirrorCount').innerText(),/666/);
 await page.locator('#customText').fill(sample);
 assert.equal(await page.locator('#characterCount').innerText(),sample.length>150?`${[...sample].length} / 400`:`${[...sample].length} / 400`);
 await page.locator('#mirrorText').check();
 await page.locator('#applyText').click();
 const n=await page.locator('#sceneList button').count();
 assert.ok(n>=9,'long message splits into real stages: '+n);
 assert.equal(await page.locator('#messagePreview').innerText(),sample);
 assert.equal(await page.locator('#sequenceEditor').isVisible(),true);
 await page.locator('#nextScene').click();
 assert.match(await page.locator('#sequenceStatus').innerText(),/^2 \/ /);
 await page.locator('#howItWorks').click();
 assert.equal(await page.locator('#physicsDialog').isVisible(),true);
 assert.equal(await page.locator('.physics-steps li').count(),6);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#physicsDialog').isVisible(),false);
 let promise=page.waitForEvent('download');
 await page.locator('#downloadProject').click();
 const file=await promise;const bytes=await readFile(await file.path(),'utf8'),project=JSON.parse(bytes);
 assert.equal(project.mirrorCount,666);assert.equal(project.text,sample);assert.equal(project.sceneIndex,1);assert.equal(project.mirrorText,true);assert.equal(project.normals.length,666);
 await page.evaluate(()=>{window.__copied='';Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async x=>{window.__copied=x;}}});});
 await page.locator('#shareProject').click();
 await page.waitForFunction(()=>Boolean(window.__copied));
 const link=await page.evaluate(()=>window.__copied);
 assert.match(link,/#p=v1\./);
 await page.goto(link,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#customText')?.value.includes('Katharina'),null,{timeout:15000});
 assert.equal(await page.locator('#mirrorDensity').inputValue(),'666');
 assert.equal(await page.locator('#mirrorText').isChecked(),true);
 await page.locator('#toggleSequence').click(); // Resume/pause explicitly before export.
 await page.locator('#shareGif').click();
 await page.locator('#quality').selectOption('compact');
 await page.locator('#duration').selectOption('3');
 assert.equal(await page.locator('#sequenceExportNote').isVisible(),true);
 assert.match(await page.locator('#sequenceExportNote').innerText(),/frames/);
 await page.locator('#projectionOnly').check();
 await page.locator('#brandGif').uncheck();
 await page.locator('#startExport').click();
 await page.locator('#downloadGif').waitFor({state:'visible',timeout:180000});
 promise=page.waitForEvent('download');
 await page.locator('#downloadGif').click();
 await (await promise).saveAs('tests/artifacts/long-love-'+name+'.gif');
 await page.locator('#closeExport').click();
 promise=page.waitForEvent('download');
 await page.locator('#savePng').click();
 const png=await promise;
 assert.match(png.suggestedFilename(),/raymosaic-scene-2-of-/);
 await png.saveAs('tests/artifacts/long-love-'+name+'.png');
 assert.deepEqual(errors,[]);
 console.log(name+' 666 mirror / '+n+' scenes / complete long GIF / project link / accessible explainer / PNG segment: PASS');
 await page.close();
 }finally{await context.close();await browser.close();}
}
